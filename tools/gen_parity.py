#!/usr/bin/env python3
"""Generate the MoonBit parity test from the Java oracle output.

The oracle (``tools/java/Oracle.java``) drives the *original*
``net.imglib2.algorithm.fft2`` bytecode over the deterministic inputs in
``build/cases`` and writes the results as raw float32 bit patterns.  This
script turns those golden results into a white box MoonBit test so that
``moon test`` verifies the port against the Java original.

Usage::

    python tools/gen_parity.py --cases build/cases --out moonbit_fft/parity_wbtest.mbt
    cd moonbit_fft && moon fmt      # the generated file is not formatted yet

The generated file and the committed one are the same file, so a change of
the generator shows up in a diff of the test and not only in a diff of the
tool.
"""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

import numpy as np

# Relative tolerance used when comparing the MoonBit result with the Java
# original.  The Java original evaluates the transform with a mixed radix
# PFA kernel in single precision while the port accumulates in double
# precision, so the two agree to single precision accuracy but not bit for
# bit.  The tolerance is relative to the magnitude of the whole result, not
# to a single sample: a sample that happens to be close to zero still carries
# the rounding error of the whole transform.
TOLERANCE = 1.0e-6
TOLERANCE_LITERAL = "1.0e-6"


def f32_literal(value: float) -> str:
    """Render a float32 value as a MoonBit expression.

    The shortest decimal that round trips through single precision is used,
    converting it to a double and back to a float therefore reproduces the
    original bits exactly.
    """
    v = np.float32(value)
    if np.isnan(v):
        return "Float::from_double(0.0)"
    text = np.format_float_positional(v, unique=True, trim="-")
    if text in ("0.", "-0."):
        return "Float::from_double(" + text + "0)"
    if "." not in text:
        text += ".0"
    return "Float::from_double(" + text + ")"


def read_f32(path: Path) -> np.ndarray:
    raw = path.read_bytes()
    count = len(raw) // 4
    return np.frombuffer(raw, dtype="<f4", count=count)


def read_oracle(path: Path) -> dict:
    """Parse one oracle output file."""
    lines = [line.strip() for line in path.read_text().splitlines() if line.strip()]
    out: dict = {"kind": None, "dims": [], "values": [], "extra": [], "status": "ok"}
    index = 0
    while index < len(lines):
        parts = lines[index].split()
        key = parts[0]
        if key == "KIND":
            out["kind"] = parts[1]
        elif key == "DIMS":
            out["dims"] = [int(v) for v in parts[1:]]
        elif key == "STATUS":
            out["status"] = parts[1]
        elif key == "N":
            count = int(parts[1])
            out["values"] = [
                struct.unpack("<f", struct.pack("<I", int(lines[index + 1 + i], 16)))[0]
                for i in range(count)
            ]
            index += count
        elif key == "EXTRA":
            count = int(parts[1])
            out["extra"] = [int(lines[index + 1 + i]) for i in range(count)]
            index += count
        index += 1
    return out


def read_manifest(path: Path) -> list:
    cases = []
    current = None
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        key = parts[0]
        if key == "CASE":
            current = {"name": parts[1]}
            cases.append(current)
        elif key == "KIND":
            current["kind"] = parts[1]
        elif key == "DIMS":
            current["dims"] = [int(v) for v in parts[1:]]
        elif key == "TARGET":
            current["target"] = [int(v) for v in parts[1:]]
        elif key == "IN":
            current["in"] = parts[1]
        elif key == "DIM":
            current["dim"] = int(parts[1])
        elif key == "SCALE":
            current["scale"] = parts[1] == "1"
        elif key == "FORWARD":
            current["forward"] = parts[1] == "1"
        elif key == "FILL":
            current["fill"] = float(parts[1])
    return cases


def ident(name: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in name)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cases", default="build/cases")
    parser.add_argument("--out", default="moonbit_fft/parity_wbtest.mbt")
    args = parser.parse_args()

    cases_dir = Path(args.cases)
    manifest = cases_dir / "manifest.txt"
    java_dir = cases_dir / "java"

    cases = read_manifest(manifest)

    body: list[str] = []
    body.append("/// Parity tests against the original Java `net.imglib2.algorithm.fft2`")
    body.append("/// implementation.")
    body.append("///")
    body.append("/// This file is generated by `tools/gen_parity.py`; every expectation")
    body.append("/// below is the output of the original Java bytecode, captured by")
    body.append("/// `tools/java/Oracle.java`.")
    body.append("")
    body.append("/// Asserts that two arrays of floats agree within the single")
    body.append("/// precision tolerance of the two different FFT kernels.")
    body.append("///")
    body.append("/// The tolerance is relative to the magnitude of the whole")
    body.append("/// expected result: a single sample may be close to zero even")
    body.append("/// though the transform that produced it was not.")
    body.append("fn parity_assert_floats(")
    body.append("  actual : Array[Float],")
    body.append("  expected : Array[Float],")
    body.append("  tolerance : Float")
    body.append(") -> Unit raise {")
    body.append("  assert_true(")
    body.append("    actual.length() == expected.length(),")
    body.append("    msg=\"expected \\{expected.length()} values, got \\{actual.length()}\",")
    body.append("  )")
    body.append("  let mut scale = Float::from_double(1.0)")
    body.append("  let mut i = 0")
    body.append("  while i < expected.length() {")
    body.append("    let magnitude = expected[i].abs()")
    body.append("    if magnitude > scale {")
    body.append("      scale = magnitude")
    body.append("    }")
    body.append("    i = i + 1")
    body.append("  }")
    body.append("  let mut i = 0")
    body.append("  while i < expected.length() {")
    body.append("    let want = expected[i]")
    body.append("    let got = actual[i]")
    body.append("    let diff = (got - want).abs()")
    body.append("    let allowed = tolerance * (scale + want.abs())")
    body.append("    assert_true(")
    body.append("      diff <= allowed,")
    body.append("      msg=\"value \\{i}: expected \\{want}, got \\{got}, allowed \\{allowed}\",")
    body.append("    )")
    body.append("    i = i + 1")
    body.append("  }")
    body.append("}")
    body.append("")
    # The integers of the extents are `Int32` and not `Int`: `Int` is the
    # default integer type of the target and its width is not the same on
    # every target, so a test that compares integers has to name the width.
    body.append("/// Asserts that two extent arrays are identical.")
    body.append("fn parity_assert_dims(actual : Array[Int32], expected : Array[Int32]) -> Unit raise {")
    body.append("  assert_true(")
    body.append("    actual.length() == expected.length(),")
    body.append("    msg=\"expected \\{expected.length()} dimensions, got \\{actual.length()}\",")
    body.append("  )")
    body.append("  let mut i = 0")
    body.append("  while i < expected.length() {")
    body.append("    assert_true(")
    body.append("      actual[i] == expected[i],")
    body.append("      msg=\"dimension \\{i}: expected \\{expected[i]}, got \\{actual[i]}\",")
    body.append("    )")
    body.append("    i = i + 1")
    body.append("  }")
    body.append("}")
    body.append("")
    body.append("/// Asserts that two arrays of integers are identical.")
    body.append("fn parity_assert_ints(actual : Array[Int32], expected : Array[Int32]) -> Unit raise {")
    body.append("  assert_true(")
    body.append("    actual.length() == expected.length(),")
    body.append("    msg=\"expected \\{expected.length()} values, got \\{actual.length()}\",")
    body.append("  )")
    body.append("  let mut i = 0")
    body.append("  while i < expected.length() {")
    body.append("    assert_true(")
    body.append("      actual[i] == expected[i],")
    body.append("      msg=\"value \\{i}: expected \\{expected[i]}, got \\{actual[i]}\",")
    body.append("    )")
    body.append("    i = i + 1")
    body.append("  }")
    body.append("}")
    body.append("")

    for case in cases:
        name = case["name"]
        key = ident(name)
        golden = read_oracle(java_dir / (name + ".txt"))
        kind = case["kind"]
        if golden["status"] == "throws" and kind != "FFT_C2R_FACTORY":
            raise SystemExit(
                "the original implementation fails for case " + name + ", "
                "which is not covered by the port"
            )
        dims = case["dims"]
        source = read_f32(Path(case["in"]))
        helpers: list[str] = []

        def emit_float_array(fname: str, values) -> None:
            body.append("fn " + fname + "() -> Array[Float] {")
            body.append("  [")
            for value in values:
                body.append("    " + f32_literal(value) + ",")
            body.append("  ]")
            body.append("}")
            body.append("")

        def emit_int_array(fname: str, values) -> None:
            body.append("fn " + fname + "() -> Array[Int32] {")
            body.append("  [" + ", ".join(str(v) for v in values) + "]")
            body.append("}")
            body.append("")

        test_lines = []
        if kind == "R2C":
            dim = case["dim"]
            complex_size = dims[dim] // 2 + 1
            out_dims = list(dims)
            out_dims[dim] = complex_size
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let input = RealImage::from_data(" + str(dims) + ", parity_in_" + key + "())")
            test_lines.append("  let output = ComplexImage::new(" + str(out_dims) + ")")
            test_lines.append(
                "  assert_true(real_to_complex(input, output, None, "
                + str(dim)
                + ", "
                + ("true" if case["scale"] else "false")
                + ") == "
                + ("true" if golden["status"] == "ok" else "false")
                + ")"
            )
            test_lines.append("  parity_assert_dims(output.dims, " + str(out_dims) + ")")
            test_lines.append("  parity_assert_floats(output.data, parity_out_" + key + "(), " + TOLERANCE_LITERAL + ")")
        elif kind == "C2C":
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let data = ComplexImage::from_data(" + str(dims) + ", parity_in_" + key + "())")
            test_lines.append(
                "  assert_true(complex_to_complex(data, "
                + str(case["dim"])
                + ", "
                + ("true" if case["forward"] else "false")
                + ", "
                + ("true" if case["scale"] else "false")
                + ") == "
                + ("true" if golden["status"] == "ok" else "false")
                + ")"
            )
            test_lines.append("  parity_assert_dims(data.dims, " + str(dims) + ")")
            test_lines.append("  parity_assert_floats(data.data, parity_out_" + key + "(), " + TOLERANCE_LITERAL + ")")
        elif kind == "JC2C":
            # The `FftComplex` of the port, the class that mirrors the
            # `FftComplex` of the original.  The original copies the input
            # into the output before it transforms it and the port does not,
            # so this is the oracle of the entry point that the image API
            # cases do not reach.
            n = dims[0]
            sign = -1 if case.get("forward", True) else 1
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let fft = FftComplex::new(" + str(n) + ")")
            test_lines.append("  let cx = parity_in_" + key + "()")
            test_lines.append(
                "  let cy = Array::make("
                + str(2 * n)
                + ", Float::from_double(0.0))"
            )
            test_lines.append(
                "  fft.complex_to_complex(" + str(sign) + ", cx, cy)"
            )
            test_lines.append(
                "  parity_assert_floats(cy, parity_out_"
                + key
                + "(), "
                + TOLERANCE_LITERAL
                + ")"
            )
        elif kind == "C2R":
            dim = case["dim"]
            real_size = 2 * (dims[dim] - 1)
            out_dims = list(dims)
            out_dims[dim] = real_size
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let input = ComplexImage::from_data(" + str(dims) + ", parity_in_" + key + "())")
            test_lines.append("  let output = RealImage::new(" + str(out_dims) + ")")
            test_lines.append(
                "  assert_true(complex_to_real(input, output, None, "
                + str(dim)
                + ", "
                + ("true" if case["scale"] else "false")
                + ") == "
                + ("true" if golden["status"] == "ok" else "false")
                + ")"
            )
            test_lines.append("  parity_assert_dims(output.dims, " + str(out_dims) + ")")
            test_lines.append("  parity_assert_floats(output.data, parity_out_" + key + "(), " + TOLERANCE_LITERAL + ")")
        elif kind == "FFT_R2C":
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let input = RealImage::from_data(" + str(dims) + ", parity_in_" + key + "())")
            test_lines.append("  let spectrum = fft_real_to_complex(input)")
            test_lines.append("  parity_assert_dims(spectrum.dims, " + str(golden["dims"]) + ")")
            test_lines.append("  parity_assert_floats(spectrum.data, parity_out_" + key + "(), " + TOLERANCE_LITERAL + ")")
        elif kind == "FFT_R2C_OOB_CONST":
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append(
                "  let input = RealImage::from_data("
                + str(dims)
                + ", parity_in_"
                + key
                + "())"
            )
            test_lines.append(
                "  let spectrum = fft_real_to_complex_with_fill(input, "
                + f32_literal(case.get("fill", 0.0))
                + ")"
            )
            test_lines.append(
                "  parity_assert_dims(spectrum.dims, " + str(golden["dims"]) + ")"
            )
            test_lines.append(
                "  parity_assert_floats(spectrum.data, parity_out_"
                + key
                + "(), "
                + TOLERANCE_LITERAL
                + ")"
            )
        elif kind == "FFT_C2C_FWD":
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let data = ComplexImage::from_data(" + str(dims) + ", parity_in_" + key + "())")
            test_lines.append("  fft_complex_to_complex_forward(data)")
            test_lines.append("  parity_assert_dims(data.dims, " + str(dims) + ")")
            test_lines.append("  parity_assert_floats(data.data, parity_out_" + key + "(), " + TOLERANCE_LITERAL + ")")
        elif kind == "FFT_C2C_INV":
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let data = ComplexImage::from_data(" + str(dims) + ", parity_in_" + key + "())")
            test_lines.append("  fft_complex_to_complex_inverse(data)")
            test_lines.append("  parity_assert_dims(data.dims, " + str(dims) + ")")
            test_lines.append("  parity_assert_floats(data.data, parity_out_" + key + "(), " + TOLERANCE_LITERAL + ")")
        elif kind == "FFT_C2R":
            dim = case["dim"]
            real_size = 2 * (dims[dim] - 1)
            out_dims = list(dims)
            out_dims[dim] = real_size
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let input = ComplexImage::from_data(" + str(dims) + ", parity_in_" + key + "())")
            test_lines.append("  let output = RealImage::new(" + str(out_dims) + ")")
            test_lines.append("  fft_complex_to_real_inplace(input, output)")
            test_lines.append("  parity_assert_dims(output.dims, " + str(out_dims) + ")")
            test_lines.append("  parity_assert_floats(output.data, parity_out_" + key + "(), " + TOLERANCE_LITERAL + ")")
        elif kind == "FFT_C2R_FACTORY":
            if golden["status"] == "throws":
                # the original reads outside the input image for this extent
                # and fails, the port has to refuse it as well
                test_lines.append(
                    "  assert_true(!fft_complex_to_real_supported("
                    + str(dims)
                    + "))"
                )
            else:
                emit_float_array("parity_in_" + key, source)
                emit_float_array("parity_out_" + key, golden["values"])
                test_lines.append(
                    "  let input = ComplexImage::from_data("
                    + str(dims)
                    + ", parity_in_"
                    + key
                    + "())"
                )
                test_lines.append("  let output = fft_complex_to_real(input)")
                test_lines.append(
                    "  parity_assert_dims(output.dims, " + str(golden["dims"]) + ")"
                )
                test_lines.append(
                    "  parity_assert_floats(output.data, parity_out_"
                    + key
                    + "(), "
                    + TOLERANCE_LITERAL
                    + ")"
                )
        elif kind == "FFT_C2R_UNPAD":
            emit_float_array("parity_in_" + key, source)
            emit_float_array("parity_out_" + key, golden["values"])
            test_lines.append("  let input = ComplexImage::from_data(" + str(dims) + ", parity_in_" + key + "())")
            test_lines.append("  let output = fft_complex_to_real_unpad(input, " + str(case["target"]) + ")")
            test_lines.append("  parity_assert_dims(output.dims, " + str(golden["dims"]) + ")")
            test_lines.append("  parity_assert_floats(output.data, parity_out_" + key + "(), " + TOLERANCE_LITERAL + ")")
        elif kind == "PAD":
            emit_int_array("parity_extra_" + key, golden["extra"])
            test_lines.append("  let padded = padding_interval_centered(Interval::new(" + str(dims) + "), " + str(case["target"]) + ")")
            test_lines.append("  let expected = parity_extra_" + key + "()")
            test_lines.append("  parity_assert_dims(padded.dims(), " + str(golden["dims"]) + ")")
            test_lines.append("  let mut i = 0")
            test_lines.append("  while i < padded.min.length() {")
            test_lines.append("    assert_true(")
            test_lines.append("      padded.min[i] == expected[2 * i],")
            test_lines.append("      msg=\"min[\\{i}]: expected \\{expected[2 * i]}, got \\{padded.min[i]}\",")
            test_lines.append("    )")
            test_lines.append("    assert_true(")
            test_lines.append("      padded.max[i] == expected[2 * i + 1],")
            test_lines.append("      msg=\"max[\\{i}]: expected \\{expected[2 * i + 1]}, got \\{padded.max[i]}\",")
            test_lines.append("    )")
            test_lines.append("    i = i + 1")
            test_lines.append("  }")
        elif kind == "UNPAD":
            emit_int_array("parity_extra_" + key, golden["extra"])
            test_lines.append("  let unpadded = unpadding_interval_centered(Interval::new(" + str(dims) + "), " + str(case["target"]) + ")")
            test_lines.append("  let expected = parity_extra_" + key + "()")
            test_lines.append("  parity_assert_dims(unpadded.dims(), " + str(golden["dims"]) + ")")
            test_lines.append("  let mut i = 0")
            test_lines.append("  while i < unpadded.min.length() {")
            test_lines.append("    assert_true(")
            test_lines.append("      unpadded.min[i] == expected[2 * i],")
            test_lines.append("      msg=\"min[\\{i}]: expected \\{expected[2 * i]}, got \\{unpadded.min[i]}\",")
            test_lines.append("    )")
            test_lines.append("    assert_true(")
            test_lines.append("      unpadded.max[i] == expected[2 * i + 1],")
            test_lines.append("      msg=\"max[\\{i}]: expected \\{expected[2 * i + 1]}, got \\{unpadded.max[i]}\",")
            test_lines.append("    )")
            test_lines.append("    i = i + 1")
            test_lines.append("  }")
        elif kind in ("DIMS_R2C", "DIMS_C2R", "DIMS_R2C_SMALL", "DIMS_C2R_SMALL"):
            emit_int_array("parity_extra_" + key, golden["extra"])
            test_lines.append("  let complex_sizes = zeros(" + str(len(dims)) + ")")
            test_lines.append("  let real_sizes = zeros(" + str(len(dims)) + ")")
            if kind in ("DIMS_R2C", "DIMS_R2C_SMALL"):
                test_lines.append(
                    "  dimensions_real_to_complex_"
                    + ("fast" if kind == "DIMS_R2C" else "small")
                    + "("
                    + str(dims)
                    + ", complex_sizes, real_sizes)"
                )
            else:
                test_lines.append(
                    "  dimensions_complex_to_real_"
                    + ("fast" if kind == "DIMS_C2R" else "small")
                    + "("
                    + str(dims)
                    + ", complex_sizes, real_sizes)"
                )
            test_lines.append("  let expected = parity_extra_" + key + "()")
            test_lines.append("  let mut i = 0")
            test_lines.append("  while i < complex_sizes.length() {")
            if kind in ("DIMS_R2C", "DIMS_R2C_SMALL"):
                # the oracle reports the padded (real) size first, the size of
                # the complex spectrum second
                test_lines.append("    assert_true(")
                test_lines.append("      real_sizes[i] == expected[2 * i],")
                test_lines.append("      msg=\"real size \\{i}: expected \\{expected[2 * i]}, got \\{real_sizes[i]}\",")
                test_lines.append("    )")
                test_lines.append("    assert_true(")
                test_lines.append("      complex_sizes[i] == expected[2 * i + 1],")
                test_lines.append("      msg=\"complex size \\{i}: expected \\{expected[2 * i + 1]}, got \\{complex_sizes[i]}\",")
                test_lines.append("    )")
            else:
                # the oracle reports the size of the complex spectrum first, the
                # size of the real result second
                test_lines.append("    assert_true(")
                test_lines.append("      complex_sizes[i] == expected[2 * i],")
                test_lines.append("      msg=\"complex size \\{i}: expected \\{expected[2 * i]}, got \\{complex_sizes[i]}\",")
                test_lines.append("    )")
                test_lines.append("    assert_true(")
                test_lines.append("      real_sizes[i] == expected[2 * i + 1],")
                test_lines.append("      msg=\"real size \\{i}: expected \\{expected[2 * i + 1]}, got \\{real_sizes[i]}\",")
                test_lines.append("    )")
            test_lines.append("    i = i + 1")
            test_lines.append("  }")
        elif kind in ("DIMS_C2C", "DIMS_C2C_SMALL"):
            emit_int_array("parity_extra_" + key, golden["extra"])
            test_lines.append("  let sizes = zeros(" + str(len(dims)) + ")")
            test_lines.append(
                "  dimensions_complex_to_complex_"
                + ("fast" if kind == "DIMS_C2C" else "small")
                + "("
                + str(dims)
                + ", sizes)"
            )
            test_lines.append("  parity_assert_ints(sizes, parity_extra_" + key + "())")
        elif kind == "SIZES":
            # the transform length tables of the original implementation, for
            # every length from 1 to the requested maximum
            maximum = case["target"][0]
            emit_int_array("parity_extra_" + key, golden["extra"])
            test_lines.append("  let expected = parity_extra_" + key + "()")
            test_lines.append("  let mut n = 1")
            test_lines.append("  while n <= " + str(maximum) + " {")
            for label, call, offset in (
                ("real fast", "nfft_fast_real(n)", 0),
                ("real small", "nfft_small_real(n)", 1),
                ("complex fast", "nfft_fast(n)", 2),
                ("complex small", "nfft_small(n)", 3),
            ):
                test_lines.append("    assert_true(")
                test_lines.append("      " + call + " == expected[4 * (n - 1) + " + str(offset) + "],")
                test_lines.append(
                    "      msg=\""
                    + label
                    + " length \\{n}: expected \\{expected[4 * (n - 1) + "
                    + str(offset)
                    + "]}, got \\{"
                    + call
                    + "}\","
                )
                test_lines.append("    )")
            test_lines.append("    n = n + 1")
            test_lines.append("  }")
        else:
            raise SystemExit("unknown kind " + kind)
        body.extend(helpers)
        body.append('test "parity ' + kind + ' ' + name + '" {')
        body.extend(test_lines)
        body.append("}")
        body.append("")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(body) + "\n", encoding="utf-8")
    print("wrote " + str(out_path) + " (" + str(len(cases)) + " cases)")


if __name__ == "__main__":
    main()
